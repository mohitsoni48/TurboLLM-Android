#!/usr/bin/env node
// Create the Play Store upload keystore, once.
//
// The password is generated HERE, on this machine, written straight into the gitignored
// local.properties, and never printed. That is deliberate: a signing password pasted into a
// chat, a terminal transcript, or a commit is a password you have to assume is compromised —
// and this particular one cannot simply be rotated (see the warning this prints).
//
// Refuses to overwrite an existing keystore. Losing or replacing the upload key after the app
// is live means Google will not accept your updates without a support reset, so destroying one
// by re-running a script is not a mistake this is willing to make on your behalf.
//
// Usage: node scripts/create-release-keystore.mjs
import { execFileSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { appendFileSync, existsSync, mkdirSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const keystoreDir = join(appRoot, 'keystore')
const keystore = join(keystoreDir, 'turbollm-upload.jks')
const localProps = join(appRoot, 'local.properties')
const ALIAS = 'turbollm-upload'

if (existsSync(keystore)) {
  console.error(`Refusing to overwrite an existing keystore:\n  ${keystore}\n`)
  console.error('If you genuinely need a new one, move the old file somewhere safe first —')
  console.error('once the app is live, replacing the upload key needs a Google support reset.')
  process.exit(1)
}

function findKeytool() {
  const candidates = []
  if (process.env.JAVA_HOME) candidates.push(join(process.env.JAVA_HOME, 'bin', 'keytool'))
  // Gradle's own toolchain, if the build declares one.
  const gradleProps = join(appRoot, 'gradle.properties')
  if (existsSync(gradleProps)) {
    const home = /^org\.gradle\.java\.home\s*=\s*(.+)$/m.exec(readFileSync(gradleProps, 'utf8'))
    if (home) candidates.push(join(home[1].trim(), 'bin', 'keytool'))
  }
  candidates.push('keytool')
  for (const c of candidates) {
    try {
      execFileSync(c, ['-help'], { stdio: 'ignore' })
      return c
    } catch {}
  }
  return null
}

const keytool = findKeytool()
if (!keytool) {
  console.error('keytool not found. Set JAVA_HOME to a JDK, or put keytool on PATH.')
  process.exit(1)
}

// base64url of 24 random bytes: 32 chars, no shell-quoting hazards, ~192 bits.
const password = randomBytes(24).toString('base64url')

mkdirSync(keystoreDir, { recursive: true })
execFileSync(keytool, [
  '-genkeypair', '-v',
  '-keystore', keystore,
  '-alias', ALIAS,
  '-keyalg', 'RSA', '-keysize', '4096',
  // Play requires a key valid well past any plausible update; ~27 years.
  '-validity', '10000',
  '-dname', 'CN=TurboLLM, OU=TurboLLM, O=TurboLLM, C=IN',
  '-storepass', password,
  '-keypass', password,
], { stdio: ['ignore', 'ignore', 'inherit'] })

// Paths use forward slashes so the value is identical on every platform; Gradle accepts them
// on Windows too, and a backslash here would be read as an escape by the properties parser.
appendFileSync(localProps, [
  '',
  '# Play Store upload signing. Generated by scripts/create-release-keystore.mjs.',
  '# local.properties is gitignored — these must never be committed.',
  `TURBOLLM_UPLOAD_STORE_FILE=${keystore.replaceAll(String.fromCharCode(92), '/')}`,
  `TURBOLLM_UPLOAD_STORE_PASSWORD=${password}`,
  `TURBOLLM_UPLOAD_KEY_ALIAS=${ALIAS}`,
  `TURBOLLM_UPLOAD_KEY_PASSWORD=${password}`,
  '',
].join('\n'))

console.log(`created upload keystore: ${keystore}`)
console.log(`alias: ${ALIAS} · RSA 4096 · valid ~27 years`)
console.log('credentials written to local.properties (gitignored, not printed here)')
console.log('')
console.log('BACK THIS UP NOW — the .jks file AND the local.properties lines, somewhere off this')
console.log('machine (password manager / encrypted backup). If you lose them after the app is')
console.log('live, you cannot ship an update without a Google support key reset.')
